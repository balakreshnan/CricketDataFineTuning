#!/usr/bin/env python3
"""Build the single-file interactive report from pulled/log_history.json + pulled/eval.json + report/template.html.

  python report/build_report.py        (run from rhea/)  ->  cricket-lora-report.html
Every number and every insight sentence is computed from the two JSON files; nothing is typed in by hand
except the run facts table (hardware, job ids), which comes from the Slurm logs.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
hist = json.loads((root / "pulled" / "log_history.json").read_text())
ev = json.loads((root / "pulled" / "eval.json").read_text())

train = [{"s": h["step"], "loss": h["loss"], "lr": h["learning_rate"], "gn": h["grad_norm"]} for h in hist if "loss" in h]
dev = [{"s": h["step"], "v": h["eval_loss"]} for h in hist if "eval_loss" in h]
STEPS, K, GB, ROWS = 1788, 4, 256, 457_689
B, F = ev["base"], ev["ft"]
types = ["overall", "run_rate", "chase_rate", "milestone"]
name = {"run_rate": "run rate", "chase_rate": "chase rate", "milestone": "milestone"}

# smoothed loss (same EMA as the page) to describe the shape of the curve
e, ema = train[0]["loss"], []
for p in train:
    e = 0.85 * e + 0.15 * p["loss"]
    ema.append(e)
first, last = train[0]["loss"], ema[-1]
half = next(p["s"] for p, v in zip(train, ema) if v <= last + 0.1 * (first - last))   # 90% of the total drop reached


def pts(x):
    return f"{x:+.2f}"


acc_b, acc_f = B["overall"]["accuracy"] * 100, F["overall"]["accuracy"] * 100
d_acc = acc_f - acc_b
lo, hi = ev["ci"]
tok_b, tok_f = B["overall"]["mean_tokens"], F["overall"]["mean_tokens"]
d_tok = (tok_f / tok_b - 1) * 100
qc, pr, tp = ev["questions_changed"], ev["pairs"], ev["tokens_p"]
per_type = sorted(((F[t]["accuracy"] - B[t]["accuracy"]) * 100, t) for t in types[1:])
worst_t = min(types[1:], key=lambda t: F[t]["accuracy"])
trunc_b = round(B["overall"]["truncated_rate"] * B["overall"]["samples"])
trunc_f = round(F["overall"]["truncated_rate"] * F["overall"]["samples"])
sig = ("The interval excludes zero, so the gain is unlikely to be chance, but its lower end is close to zero."
       if lo > 0 else "The interval includes zero, so this change is within sampling noise."
       if hi > 0 else "The interval is entirely below zero: accuracy got worse.")

insights = [
    f"<b>Accuracy moved from {acc_b:.2f}% to {acc_f:.2f}% ({pts(d_acc)} points).</b> A bootstrap over the 600 questions "
    f"puts the 95% interval at {pts(lo)} to {pts(hi)} points. {sig} {qc['better']} questions improved, {qc['worse']} "
    f"got worse and {qc['same']} were unchanged.",
    f"<b>The clearer effect is shorter reasoning: {tok_b:,.0f} to {tok_f:,.0f} tokens per answer ({d_tok:+.0f}%).</b> "
    f"The median fell from {tp['base']['50']:,} to {tp['ft']['50']:,} tokens and the long tail collapsed: the 99th "
    f"percentile went from {tp['base']['99']:,} to {tp['ft']['99']:,}.",
    f"<b>No answer ran into the token cap after fine-tuning.</b> The base model was cut off on {trunc_b} of "
    f"{B['overall']['samples']:,} samples ({B['overall']['truncated_rate'] * 100:.2f}%); the fine-tuned model on {trunc_f}.",
    "<b>By question type:</b> " + ", ".join(
        f"{name[t]} {B[t]['accuracy'] * 100:.2f}% to {F[t]['accuracy'] * 100:.2f}% ({pts(d)})" for d, t in reversed(per_type))
    + f". {name[worst_t].capitalize()} is still the weakest type after fine-tuning.",
    f"<b>The base model was already near its ceiling.</b> Both models got every one of the 600 questions right in at "
    f"least one of {K} samples, so the remaining errors are occasional slips, not questions the model cannot solve. "
    f"Of {sum(pr.values()):,} paired samples, {pr['fixed']} were right only after fine-tuning and {pr['broken']} only before.",
    f"<b>Training loss settled early.</b> It started at {first:.3f} and 90% of its total drop was done by step {half} of "
    f"{STEPS:,}; dev loss then drifted from {dev[0]['v']:.4f} (step {dev[0]['s']}) to {dev[-1]['v']:.4f} and never rose, "
    f"so there is no sign of overfitting within one epoch. A small drop is expected here: the traces were generated by "
    f"this same base model, so the adapter is learning which of its own answers to prefer, not new skills.",
    "<b>Limits of this benchmark:</b> it has 600 questions covering three of the dataset's six question types "
    "(projection, strike rate and legal balls are trained on but not tested), sampled at temperature 1.0.",
]

data = {
    "types": types, "train": train, "dev": dev, "insights": insights,
    "lede": (f"One epoch of LoRA fine-tuning on {ROWS:,} cricket reasoning traces, then the base and fine-tuned models on "
             f"the same 600 held-out questions, {K} samples each. Accuracy rose {pts(d_acc)} points and answers got "
             f"{abs(d_tok):.0f}% shorter."),
    "evalSub": (f"Both models answered the dataset's 600-question eval split in thinking mode, {K} samples per question "
                f"({B['overall']['samples']:,} samples per model), same prompts, seed and sampling settings "
                f"(temperature 1.0, top-p 0.95, top-k 20). An answer counts only if it finishes and the final number "
                f"matches the exact answer."),
    "eval": {"base": B, "ft": F, "k": K, "ci": ev["ci"], "max_new_tokens": 4096, "samples": B["overall"]["samples"]},
    "hist": ev["hist"], "pairs": pr, "example": ev.get("example"),
    "facts": {"steps": STEPS, "global_batch": GB, "train_rows": ROWS, "train_hours": "4.5", "gpus": 32, "nodes": 8},
    "factRows": [
        ["Base model", "Qwen/Qwen3.8-27B"],
        ["Dataset", "Balab2021/CricketData-T20-Reasoning-Qwen3.8-Full (458,702 training rows; 13 dropped for length, 1,000 held out for dev loss)"],
        ["Method", "LoRA r=32, alpha=64, dropout 0.05 on attention, Gated-DeltaNet and MLP projections; 217.6M trainable parameters (0.79%)"],
        ["Schedule", "1 epoch, 1,788 steps, global batch 256, learning rate 1e-4 with 3% warmup and cosine decay, bf16, max 6,144 tokens"],
        ["Hardware", "Rhea: 8 nodes x 4 NVIDIA Vera Rubin GPUs (286 GB each), DDP; Slurm job 23649, 4 h 30 min of training"],
        ["Benchmark", "Slurm jobs 25585 (base) and 25847 (fine-tuned, adapter merged), 4 nodes each, Hugging Face generate"],
        ["Adapter", "Balab2021/Qwen3.8-27B-Cricket-Reasoning-Rhea-LoRA (private)"],
    ],
    "foot": "Built from the trainer's log history and the per-sample benchmark records of this run. "
            "Loss values are logged every 5 steps; dev loss every 200 steps.",
}
html = (root / "report" / "template.html").read_text(encoding="utf-8")
assert "/*DATA*/null" in html
out = root / "cricket-lora-report.html"
out.write_text(html.replace("/*DATA*/null", json.dumps(data, ensure_ascii=False).replace("</", "<\\/")), encoding="utf-8", newline="\n")
print("wrote", out, f"{out.stat().st_size / 1024:.0f} KB")
for i in insights:
    print("-", i[:150])
